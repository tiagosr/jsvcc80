/**
 * Z80 Code Generator - transforms IR to Z80 assembly
 */
import { 
  Instruction, BasicBlock, FunctionIR, ProgramIR,
  LoadInstruction, StoreInstruction, BinaryOpInstruction, UnaryOpInstruction,
  CallInstruction, ReturnInstruction, JumpIfInstruction, JumpInstruction,
  LabelInstruction, AllocStackInstruction, FreeStackInstruction, PushInstruction, PopInstruction
} from '../nanopass/il.js';

/**
 * Z80 Register names used in code generation
 */
export const Registers = {
  A: 'a',      // Accumulator (primary)
  B: 'b',      // General purpose register pair BC
  C: 'c',      // General purpose register pair BC
  D: 'd',      // General purpose register pair DE
  E: 'e',      // General purpose register pair DE
  H: 'h',      // General purpose register pair HL
  L: 'l',      // General purpose register pair HL
  IX: 'ix',    // Index register X
  IY: 'iy',    // Index register Y
  SP: 'sp',    // Stack pointer
  PC: 'pc'     // Program counter (implicit)
};

/**
 * Z80 Code Generator class
 */
export class Z80Codegen {
  /**
   * Creates a new Z80 code generator
   * @param {Object} options - Generation options
   */
  constructor(options = {}) {
    this.options = {
      outputDebugInfo: false,
      optimizeStack: true,
      ...options
    };

    this.currentFunction = null;
    this.labelsUsed = new Set();
    this.tempVariables = new Map();
    this.nextTempId = 0;
    
    // Generated assembly code buffer
    this.codeLines = [];
  }

  /**
   * Generates Z80 assembly from a program IR
   * @param {ProgramIR} ir - Program intermediate representation
   * @returns {string} Generated Z80 assembly source
   */
  generate(ir) {
    this.reset();
    
    // Generate header
    this.generateHeader();

    // Generate global data section
    if (ir.globals && ir.globals.length > 0) {
      this.codeLines.push('');
      this.codeLines.push('; Global Data Section');
      for (const global of ir.globals) {
        this.generateGlobal(global);
      }
    }

    // Generate functions
    if (ir.functions && ir.functions.length > 0) {
      for (const func of ir.functions) {
        this.currentFunction = func;
        this.codeLines.push('');
        this.generateFunction(func);
      }
    }

    return this.codeLines.join('\n') + '\n';
  }

  /**
   * Resets internal state for new code generation
   */
  reset() {
    this.currentFunction = null;
    this.labelsUsed.clear();
    this.tempVariables.clear();
    this.nextTempId = 0;
    this.codeLines = [];
  }

  /**
   * Generates the assembler header/directives
   */
  generateHeader() {
    this.codeLines.push('; Generated by vcc80 - Z80 C Compiler');
    this.codeLines.push('');
    this.codeLines.push('; Entry point (optional)');
    this.codeLines.push('');
  }

  /**
   * Generates a global variable definition
   * @param {Object} global - Global variable descriptor
   */
  generateGlobal(global) {
    const name = global.name;
    
    if (global.type === 'data') {
      // Data declaration: db, dw
      if (global.value !== undefined) {
        this.codeLines.push(`${name}: .db ${this.formatValue(global.value)}`);
      } else {
        // Reserved space
        const size = global.size || 1;
        this.codeLines.push(`${name}: .ds ${size}`);
      }
    } else if (global.type === 'bss') {
      // Uninitialized data
      this.codeLines.push(`${name}: .ds ${global.size || 1}`);
    }
  }

  /**
   * Generates a complete function definition
   * @param {FunctionIR} func - Function IR
   */
  generateFunction(func) {
    const name = func.name;
    
    this.codeLines.push('');
    this.codeLines.push('; Function: ' + name);
    this.codeLines.push(`${name}:`);

    // Generate prologue if needed (stack setup)
    this.generatePrologue(func);

    // Generate basic blocks in order
    for (const block of func.blocks) {
      this.generateBasicBlock(block);
    }

    // Generate epilogue
    this.generateEpilogue(func);
  }

  /**
   * Generates function prologue (stack frame setup)
   * @param {FunctionIR} func - Function IR
   */
  generatePrologue(func) {
    // Z80 doesn't have a dedicated stack frame pointer by default,
    // but we can use IX or IY if needed
    
    // Check if any local variables need allocation
    const needsStack = func.blocks.some(block => 
      block.instructions.some(instr => instr instanceof AllocStackInstruction)
    );

    if (needsStack && this.options.optimizeStack) {
      // Calculate total stack space needed
      let totalSpace = 0;
      for (const block of func.blocks) {
        for (const instr of block.instructions) {
          if (instr instanceof AllocStackInstruction) {
            totalSpace += instr.operands[0];
          }
        }
      }

      if (totalSpace > 0) {
        this.codeLines.push(`  ld ${Registers.SP}, hl`);
        this.codeLines.push(`  ld hl, stack_top_${this.currentFunction.name}`);
        this.codeLines.push(`  sub a`); // Clear A before subtraction
        this.codeLines.push(`  ld l, a`);
      }
    }
  }

  /**
   * Generates function epilogue (stack frame teardown)
   * @param {FunctionIR} func - Function IR
   */
  generateEpilogue(func) {
    // Restore stack pointer before return
    if (this.options.optimizeStack) {
      this.codeLines.push(`  ld ${Registers.SP}, hl`);
      this.codeLines.push(`  ld hl, stack_top_${func.name}`);
    }

    this.codeLines.push('  ret');
  }

  /**
   * Generates a basic block of instructions
   * @param {BasicBlock} block - Basic block to generate
   */
  generateBasicBlock(block) {
    // Generate label if not already generated (entry point)
    const isEntry = block === this.currentFunction.blocks[0];
    
    for (const instr of block.instructions) {
      this.generateInstruction(instr);
    }

    // Handle implicit fall-through to successor
    if (!isEntry && block.successor) {
      // Check if last instruction was already a jump
      const lastInstr = block.instructions[block.instructions.length - 1];
      if (!(lastInstr instanceof JumpInstruction || 
            lastInstr instanceof JumpIfInstruction)) {
        this.codeLines.push(`  jp ${block.successor.name}`);
      }
    }
  }

  /**
   * Generates a single IL instruction to Z80 assembly
   * @param {Instruction} instr - Instruction to generate
   */
  generateInstruction(instr) {
    switch (instr.opcode) {
      case 'LOAD':
        this.generateLoad(instr);
        break;

      case 'STORE':
        this.generateStore(instr);
        break;

      case 'BINOP':
        this.generateBinaryOp(instr);
        break;

      case 'UNOP':
        this.generateUnaryOp(instr);
        break;

      case 'CALL':
        this.generateCall(instr);
        break;

      case 'RET':
        this.generateReturn(instr);
        break;

      case 'JUMP_IF':
        this.generateJumpIf(instr);
        break;

      case 'JUMP':
        this.generateJump(instr);
        break;

      case 'LABEL':
        // Labels are generated at block level, skip here
        break;

      case 'ALLOC_STACK':
        this.generateAllocStack(instr);
        break;

      case 'FREE_STACK':
        this.generateFreeStack(instr);
        break;

      case 'PUSH':
        this.generatePush(instr);
        break;

      case 'POP':
        this.generatePop(instr);
        break;

      default:
        console.warn(`Unknown instruction opcode: ${instr.opcode}`);
    }
  }

  /**
   * Generates a LOAD instruction
   * @param {LoadInstruction} instr - Load instruction
   */
  generateLoad(instr) {
    const [dest, src] = instr.operands;

    // Immediate load to register pair (HL for 16-bit)
    if (src.startsWith('#') || /^\d+$/.test(src)) {
      this.codeLines.push(`  ld hl, ${this.formatValue(src)}`);
      return;
    }

    // Load from memory address into HL
    if (typeof src === 'string' && !dest.startsWith('hl')) {
      this.codeLines.push(`  ld hl, (${src})`);
    } else {
      // Load value to register
      const reg = this.formatRegister(dest);
      this.codeLines.push(`  ld ${reg}, ${this.formatValue(src)}`);
    }
  }

  /**
   * Generates a STORE instruction
   * @param {StoreInstruction} instr - Store instruction
   */
  generateStore(instr) {
    const [dest, src] = instr.operands;

    // Store HL to memory address
    if (src === 'hl') {
      this.codeLines.push(`  ld (${dest}), hl`);
    } else {
      // Load value into HL first
      const reg = this.formatRegister(src);
      this.codeLines.push(`  ld ${reg}, a`); // Assuming src is A register
      this.codeLines.push(`  ld (${dest}), ${reg}`);
    }
  }

  /**
   * Generates a binary operation instruction
   * @param {BinaryOpInstruction} instr - Binary op instruction
   */
  generateBinaryOp(instr) {
    const [dest, op, src1, src2] = instr.operands;
    
    // Most Z80 operations work with accumulator (A), so we need to be careful
    this.codeLines.push(`  ld a, ${src1}`);

    switch (op) {
      case 'add':
        this.codeLines.push(`  add a, ${src2}`);
        break;

      case 'sub':
        this.codeLines.push(`  sub ${src2}`);
        break;

      case 'mul':
        // Z80 doesn't have mul - use repeated addition or table lookup
        this.codeLines.push(`  ld b, a`);
        this.codeLines.push(`  xor a`);
        this.codeLines.push(`  ld c, ${src2}`);
        this.codeLines.push('mul_loop:');
        this.codeLines.push(`  add a, b`);
        this.codeLines.push(`  dec c`);
        this.codeLines.push('  jp nz, mul_loop');
        break;

      case 'div':
        // Division requires more complex implementation
        this.codeLines.push(`  ld b, ${src2}`);
        this.codeLines.push(`  ld a, 0`); // Quotient in A
        this.codeLines.push('div_loop:');
        // Simplified division - placeholder for full implementation
        break;

      case 'and':
        this.codeLines.push(`  and ${src2}`);
        break;

      case 'or':
        this.codeLines.push(`  or ${src2}`);
        break;

      case 'xor':
        this.codeLines.push(`  xor ${src2}`);
        break;

      default:
        console.warn(`Unknown binary operation: ${op}`);
    }

    // Store result to destination
    const reg = this.formatRegister(dest, true); // 8-bit register
    if (reg !== 'a') {
      this.codeLines.push(`  ld ${reg}, a`);
    }
  }

  /**
   * Generates a unary operation instruction
   * @param {UnaryOpInstruction} instr - Unary op instruction
   */
  generateUnaryOp(instr) {
    const [dest, op, src] = instr.operands;

    this.codeLines.push(`  ld a, ${src}`);

    switch (op) {
      case 'neg':
        // Two's complement negation: cpl + 1
        this.codeLines.push('  cpl');
        this.codeLines.push('  inc a');
        break;

      case 'not':
        // One's complement
        this.codeLines.push('  cpl');
        break;

      default:
        console.warn(`Unknown unary operation: ${op}`);
    }

    const reg = this.formatRegister(dest, true);
    if (reg !== 'a') {
      this.codeLines.push(`  ld ${reg}, a`);
    }
  }

  /**
   * Generates a CALL instruction
   * @param {CallInstruction} instr - Call instruction
   */
  generateCall(instr) {
    const [func, ...args] = instr.operands;

    // Push arguments onto stack (right-to-left for Z80 convention)
    for (const arg of args.reverse()) {
      this.codeLines.push(`  ld a, ${arg}`);
      this.codeLines.push('  push af');
    }

    // Perform the call
    this.codeLines.push(`  call ${func}`);

    // Clean up stack arguments (assuming 1-byte arguments)
    if (args.length > 0) {
      const bytes = args.length * 2; // Each argument was pushed as AF (2 bytes)
      this.codeLines.push(`  ld hl, sp`);
      this.codeLines.push(`  add hl, bc`); // Assuming BC has byte count
      this.codeLines.push('  ld sp, hl');
    }
  }

  /**
   * Generates a RETURN instruction
   * @param {ReturnInstruction} instr - Return instruction
   */
  generateReturn(instr) {
    const [value] = instr.operands;

    if (value && value !== 'null') {
      // Load return value into A register
      this.codeLines.push(`  ld a, ${value}`);
    }

    this.codeLines.push('  ret');
  }

  /**
   * Generates a conditional jump instruction
   * @param {JumpIfInstruction} instr - Conditional jump instruction
   */
  generateJumpIf(instr) {
    const [condition, value, target] = instr.operands;

    // Load value into A for comparison
    this.codeLines.push(`  ld a, ${value}`);

    switch (condition) {
      case 'eq':
        this.codeLines.push('  xor a');
        this.codeLines.push(`  jp z, ${target}`);
        break;

      case 'ne':
        this.codeLines.push('  xor a');
        this.codeLines.push(`  jp nz, ${target}`);
        break;

      case 'lt':
        // Less than: value < 0 (signed comparison)
        this.codeLines.push('  cp 0');
        this.codeLines.push(`  jp nc, skip_${target}`);
        this.codeLines.push(`  jp ${target}`);
        this.labelsUsed.add(`skip_${target}`);
        break;

      case 'le':
        // Less or equal: value <= 0
        this.codeLines.push('  cp 0');
        this.codeLines.push(`  jp p, skip_${target}`);
        this.codeLines.push(`  jp ${target}`);
        this.labelsUsed.add(`skip_${target}`);
        break;

      case 'gt':
        // Greater than: value > 0
        this.codeLines.push('  cp 0');
        this.codeLines.push(`  jp m, skip_${target}`);
        this.codeLines.push(`  jp ${target}`);
        this.labelsUsed.add(`skip_${target}`);
        break;

      case 'ge':
        // Greater or equal: value >= 0
        this.codeLines.push('  cp 0');
        this.codeLines.push(`  jp m, skip_${target}`);
        this.codeLines.push(`  jp ${target}`);
        this.labelsUsed.add(`skip_${target}`);
        break;

      default:
        console.warn(`Unknown condition: ${condition}`);
    }
  }

  /**
   * Generates an unconditional jump instruction
   * @param {JumpInstruction} instr - Jump instruction
   */
  generateJump(instr) {
    const [target] = instr.operands;
    this.codeLines.push(`  jp ${target}`);
  }

  /**
   * Generates a stack allocation instruction
   * @param {AllocStackInstruction} instr - Stack allocation instruction
   */
  generateAllocStack(instr) {
    const [bytes] = instr.operands;
    
    // Allocate space by adjusting SP (Z80 stack grows downward)
    this.codeLines.push(`  ld bc, ${bytes}`);
    this.codeLines.push('  add hl, sp');
    this.codeLines.push('  ld sp, hl');
  }

  /**
   * Generates a stack deallocation instruction
   * @param {FreeStackInstruction} instr - Stack deallocation instruction
   */
  generateFreeStack(instr) {
    const [bytes] = instr.operands;
    
    // Deallocate space by adjusting SP
    this.codeLines.push(`  ld bc, ${bytes}`);
    this.codeLines.push('  sub a');
    this.codeLines.push('  ld l, a');
    this.codeLines.push('  add hl, sp');
    this.codeLines.push('  ld sp, hl');
  }

  /**
   * Generates a PUSH instruction (for function call arguments)
   * @param {PushInstruction} instr - Push instruction
   */
  generatePush(instr) {
    const [value] = instr.operands;
    
    // Z80 has push/pop for register pairs, not single registers
    this.codeLines.push(`  ld a, ${value}`);
    this.codeLines.push('  push af');
  }

  /**
   * Generates a POP instruction (for function call arguments)
   * @param {PopInstruction} instr - Pop instruction
   */
  generatePop(instr) {
    const [dest] = instr.operands;
    
    this.codeLines.push('  pop af');
    if (dest !== 'a') {
      const reg = this.formatRegister(dest, true);
      this.codeLines.push(`  ld ${reg}, a`);
    }
  }

  /**
   * Formats a register name for output
   * @param {string} reg - Register identifier
   * @param {boolean} [is8Bit=false] - Whether it's an 8-bit register
   * @returns {string} Formatted register name
   */
  formatRegister(reg, is8Bit = false) {
    const lowerReg = reg.toLowerCase();

    if (lowerReg === 'a' || lowerReg === Registers.A) return 'a';
    if (lowerReg === 'b' || lowerReg === Registers.B) return 'b';
    if (lowerReg === 'c' || lowerReg === Registers.C) return 'c';
    if (lowerReg === 'd' || lowerReg === Registers.D) return 'd';
    if (lowerReg === 'e' || lowerReg === Registers.E) return 'e';
    if (lowerReg === 'h' || lowerReg === Registers.H) return 'hl';
    if (lowerReg === Registers.L) return 'l';

    // 16-bit registers
    if (lowerReg === Registers.IX) return 'ix';
    if (lowerReg === Registers.IY) return 'iy';
    if (lowerReg === Registers.SP) return 'sp';

    throw new Error(`Unknown register: ${reg}`);
  }

  /**
   * Formats a value for output
   * @param {string|number} value - Value to format
   * @returns {string} Formatted value string
   */
  formatValue(value) {
    if (typeof value === 'number') {
      return value.toString(16).toUpperCase(); // Hex format
    }

    if (typeof value === 'string') {
      if (value.startsWith('#')) {
        return parseInt(value.slice(1), 16);
      }
      if (/^#/.test(value)) {
        return parseInt(value, 16);
      }
      // Symbol reference or label
      return value;
    }

    return String(value);
  }

  /**
   * Gets the generated assembly code
   * @returns {string} Assembly source
   */
  getCode() {
    return this.codeLines.join('\n');
  }
}
